expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
expect(errors).toEqual([])
// Contrast of every rendered heatmap cell uses the actual WCAG luminance formula.
const badContrast=await page.locator('.cal-cell:not(:disabled)').evaluateAll(elements=>{
 const luminance=c=>{const values=c.match(/[\d.]+/g).slice(0,3).map(Number).map(x=>x/255).map(x=>x<=.04045?x/12.92:((x+.055)/1.055)**2.4);return values[0]*.2126+values[1]*.7152+values[2]*.0722}
 return elements.filter(el=>{const s=getComputedStyle(el);const a=luminance(s.color),b=luminance(s.backgroundColor);return (Math.max(a,b)+.05)/(Math.min(a,b)+.05)<4.5}).length
})
expect(badContrast).toBe(0)
fs.writeFileSync('artifacts/browser-results.json',JSON.stringify({status:'PASS',errors,mobileOverflow:false,heatmapContrastFailures:badContrast,checks:['real initial values','month selection updates map','calibrated series','bbox filtering','calibration scope guard','missing VIIRS before 2012','full history','shared color mode','modal Escape and focus restoration','mobile layout','heatmap contrast']},null,2))
